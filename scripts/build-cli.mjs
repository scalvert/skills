#!/usr/bin/env node
// Builds the plugin's scripts from cli/:
//
//   shared/scalvert/scripts/agent-review.mjs   the CLI, commander bundled in
//   shared/scalvert/scripts/guard.mjs          the hook and shim guard
//   shared/scalvert/scripts/lenses/            lens prompts
//
// shared/scalvert/scripts/ is build output. Edit cli/, never the bundles.
// `npm run check:fresh` fails when a committed bundle is stale.

import { cpSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { build } from "esbuild";

const { version } = JSON.parse(readFileSync("package.json", "utf8"));

// commander and the review harness (agent-review) are bundled into every copy
// of agent-review.mjs, so every copy carries their full license text, as the
// MIT license requires. legalComments stays off because both ship their
// license as a file, not as comments.
const notice = (dir, url) => {
  const pkg = JSON.parse(readFileSync(`node_modules/${dir}/package.json`, "utf8"));
  const license = readFileSync(`node_modules/${dir}/LICENSE`, "utf8").trim();
  return [
    "/*",
    ` * This file includes ${pkg.name} ${pkg.version} (${url}), under this license:`,
    " *",
    ...license.split("\n").map((line) => (line ? ` * ${line}` : " *")),
    " */",
  ].join("\n");
};
const commanderNotice = [
  notice("commander", "https://github.com/tj/commander.js"),
  notice("agent-review", "https://github.com/scalvert/agent-review"),
].join("\n");

const out = "shared/scalvert/scripts";
const generated = "// Generated by scripts/build-cli.mjs from cli/. Do not edit.";
const common = { bundle: true, platform: "node", format: "esm", target: "node22", legalComments: "none", logLevel: "warning" };

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
await build({
  ...common,
  entryPoints: ["cli/src/bin/agent-review.mjs"],
  outfile: `${out}/agent-review.mjs`,
  define: { __AGENT_REVIEW_VERSION__: JSON.stringify(version) },
  banner: { js: `${generated}\n${commanderNotice}` },
});
await build({ ...common, entryPoints: ["cli/src/guard.mjs"], outfile: `${out}/guard.mjs`, banner: { js: generated } });
cpSync("cli/src/lenses", `${out}/lenses`, { recursive: true });
console.log(`build-cli: ${out} <- agent-review.mjs, guard.mjs, lenses/`);
